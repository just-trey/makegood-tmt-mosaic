// Generates the built-in tileable pattern library in public/patterns/ — seeded,
// deterministic procedural animal-print SVGs (cow/dalmatian/zebra/tiger) for Fill mode.
// The committed SVGs are the real artifacts; this script is the reproducible recipe for
// them (tweak a pattern's params below and re-run to regenerate).
//
//   node scripts/gen-patterns.mjs
//
// Tileability comes from drawing every blob/streak at all 9 positions of a 3x3 wrap
// (itself + 8 neighbors offset by ±one tile width/height), then clipping each copy to the
// tile rectangle with Sutherland-Hodgman. A shape that crosses an edge contributes matching
// partial pieces on both sides of that edge, so translating the tile by exactly one period
// and unioning (what the app's fill engine does at runtime) welds them back into the same
// shape with no seam — see tileFeature in src/geometry/patterns.ts.
//
// The field-traced pattern (zebra) gets there differently: its scalar field is exactly periodic
// in (W,H), so tracing its contours and clipping to the tile gives pieces that line up with the
// next tile by construction — provided no contour is dropped on the way. See
// marchingSquaresContours/closeOpenChains, and the seam assertion in tests/patterns-assets.test.ts.
//
// Deliberately avoids <circle> elements: assembly mode's rect/wheel placement auto-detects
// the largest <circle> in a loaded SVG as a design-boundary anchor (ParsedSVG.rawSVGCircle),
// which patterns must never trigger. Every shape — including the full-bleed background field —
// is emitted as a <path>.
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const OUT_DIR = resolve(REPO, 'public/patterns');
mkdirSync(OUT_DIR, { recursive: true });

// Deterministic PRNG (mulberry32) — same seed always produces the same pattern, so a
// generated SVG can be regenerated byte-for-byte and reviewed as a diff.
function mulberry32(seed) {
  let s = seed >>> 0;
  return function () {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shoelaceArea(pts) {
  let a = 0;
  for (let i = 0; i < pts.length; i++) {
    const [x1, y1] = pts[i];
    const [x2, y2] = pts[(i + 1) % pts.length];
    a += x1 * y2 - x2 * y1;
  }
  return Math.abs(a) / 2;
}

/**
 * Sutherland-Hodgman clip of a simple (non-self-intersecting) subject polygon — array of
 * [x,y], not closed (no repeated last point) — against an axis-aligned rectangle. The clip
 * window is convex, which is all Sutherland-Hodgman requires of it; the subject can be any
 * simple polygon, including the non-convex blobs this script generates.
 */
function clipToRect(subject, xmin, ymin, xmax, ymax) {
  const inside = [
    (p) => p[0] >= xmin,
    (p) => p[0] <= xmax,
    (p) => p[1] >= ymin,
    (p) => p[1] <= ymax,
  ];
  const intersect = [
    (a, b) => [xmin, a[1] + ((xmin - a[0]) / (b[0] - a[0])) * (b[1] - a[1])],
    (a, b) => [xmax, a[1] + ((xmax - a[0]) / (b[0] - a[0])) * (b[1] - a[1])],
    (a, b) => [a[0] + ((ymin - a[1]) / (b[1] - a[1])) * (b[0] - a[0]), ymin],
    (a, b) => [a[0] + ((ymax - a[1]) / (b[1] - a[1])) * (b[0] - a[0]), ymax],
  ];
  let output = subject;
  for (let e = 0; e < 4 && output.length; e++) {
    const input = output;
    output = [];
    for (let i = 0; i < input.length; i++) {
      const curr = input[i];
      const prev = input[(i - 1 + input.length) % input.length];
      const currIn = inside[e](curr);
      const prevIn = inside[e](prev);
      if (currIn) {
        if (!prevIn) output.push(intersect[e](prev, curr));
        output.push(curr);
      } else if (prevIn) {
        output.push(intersect[e](prev, curr));
      }
    }
  }
  return output;
}

/**
 * One organic blob outline as a closed polygon in local space, centered at the origin.
 * Radius is modulated by a few random smooth harmonics (not per-vertex noise) so the edge
 * reads as an irregular but smooth curve rather than a jagged polyline. `elong` stretches
 * the blob along its local x-axis — used for cow patches and dalmatian/tiger spots.
 */
function noisyBlob(rng, { r, elong = 1, amp = 0.18, segs = 28 }) {
  const harmonics = [1, 2, 3].map((k) => ({
    k: k + (rng() < 0.3 ? 1 : 0),
    amp: (amp * (0.5 + rng())) / k,
    phase: rng() * Math.PI * 2,
  }));
  const pts = [];
  for (let i = 0; i < segs; i++) {
    const theta = (i / segs) * Math.PI * 2;
    let rad = 1;
    for (const h of harmonics) rad += h.amp * Math.sin(h.k * theta + h.phase);
    pts.push([Math.cos(theta) * r * rad * elong, Math.sin(theta) * r * rad]);
  }
  return pts;
}

/**
 * A tapered, gently curved streak (real zebra/tiger stripes narrow to a point at both ends
 * and bend along their length — a stretched ellipse reads as a mechanical blob instead).
 * Builds a centerline with a random bend, then a left/right offset polygon whose half-width
 * follows a sine taper (0 at both ends) plus a little jitter so the edge isn't a perfect
 * curve. Centered lengthwise and widthwise at the origin, in local (unrotated) space.
 */
function streak(rng, { length, width, bend = 0.18, segs = 32 }) {
  const bendAmp = length * bend * (0.5 + rng());
  const bendFreq = 0.6 + rng() * 0.8;
  const bendPhase = rng() * Math.PI * 2;
  const jitterAmp = width * 0.12;
  const jitterFreq = 3 + rng() * 3;
  const jitterPhase = rng() * Math.PI * 2;
  const centerline = [];
  for (let i = 0; i <= segs; i++) {
    const t = i / segs;
    const x = -length / 2 + t * length;
    const y = bendAmp * Math.sin(t * Math.PI * bendFreq + bendPhase);
    centerline.push([x, y]);
  }
  const left = [],
    right = [];
  for (let i = 0; i < centerline.length; i++) {
    const t = i / segs;
    const [px, py] = centerline[i];
    const [ax, ay] = centerline[Math.max(0, i - 1)];
    const [bx, by] = centerline[Math.min(centerline.length - 1, i + 1)];
    let dx = bx - ax,
      dy = by - ay;
    const len = Math.hypot(dx, dy) || 1;
    dx /= len;
    dy /= len;
    const nx = -dy,
      ny = dx;
    const taper = Math.pow(Math.sin(Math.PI * t), 0.55); // wide through the middle, sharp points at the ends
    const jitter = 1 + jitterAmp * Math.sin(t * Math.PI * jitterFreq + jitterPhase);
    const w = (width / 2) * taper * jitter;
    left.push([px + nx * w, py + ny * w]);
    right.push([px - nx * w, py - ny * w]);
  }
  return [...left, ...right.reverse()];
}

/**
 * A scalar field for organic branching/merging stripes (real zebra fur, unlike independently
 * placed streaks, has stripes that split and rejoin) — built from a dominant sine term at
 * integer frequency (kx,ky) plus a few smaller "wobble" terms, also at integer frequencies.
 * Every term individually satisfies term(x+W,y) = term(x,y) (sin of an integer multiple of
 * 2π added to the argument), so the whole field — and cos(2π·field) below — is *exactly*
 * periodic over one WxH tile: sampling it at any real (x,y), including outside [0,W]x[0,H],
 * reproduces the same values one period over. That's what lets the marching-squares contours
 * extracted from it tile seamlessly (see marchingSquaresContours).
 */
function stripeField(rng, { kx, ky, wobbleTerms, wobbleAmp }) {
  const terms = [{ kx, ky, amp: 1, phase: 0 }];
  for (let i = 0; i < wobbleTerms; i++) {
    terms.push({
      kx: kx + Math.round((rng() - 0.5) * 4),
      ky: ky + Math.round((rng() - 0.5) * 4),
      amp: (wobbleAmp * (0.4 + rng())) / (i + 1),
      phase: rng() * Math.PI * 2,
    });
  }
  return (x, y, W, H) => {
    let phase = 0;
    for (const t of terms)
      phase += t.amp * Math.sin(2 * Math.PI * ((t.kx * x) / W + (t.ky * y) / H) + t.phase);
    return 0.5 + 0.5 * Math.cos(2 * Math.PI * phase);
  };
}

/**
 * Marching squares over a padded grid, linked into closed loops. `field` must be periodic in
 * (W,H) — see stripeField. Padding samples past the true tile edges so the contours near them are
 * traced in context; the caller clips the result down to the real [0,W]x[0,H] tile with
 * clipToRect, same as the blob wrap-and-clip, and the field's periodicity guarantees the pieces
 * left on either side of a cut line up with the next tile over.
 *
 * A branching stripe field spans the window, so plenty of contours can't close inside it however
 * much padding it gets — those are closed against the window border instead (see
 * closeOpenChains), not discarded. Returned loops are wound with the >threshold side on the left,
 * so an enclosed white island comes back as a loop of opposite sign to the stripe around it.
 */
function marchingSquaresContours(field, W, H, { res, padMM, threshold }) {
  const pad = Math.round(padMM * res);
  const nx = Math.round(W * res) + pad * 2;
  const ny = Math.round(H * res) + pad * 2;
  const x0 = -padMM,
    y0 = -padMM;
  const dx = 1 / res,
    dy = 1 / res;
  const grid = [];
  for (let j = 0; j <= ny; j++) {
    const row = new Float64Array(nx + 1);
    for (let i = 0; i <= nx; i++) row[i] = field(x0 + i * dx, y0 + j * dy, W, H);
    grid.push(row);
  }
  const lerp = (a, b, va, vb) => a + ((threshold - va) / (vb - va)) * (b - a);

  const segments = [];
  const CASES = {
    1: ['left', 'bottom'],
    2: ['bottom', 'right'],
    3: ['left', 'right'],
    4: ['right', 'top'],
    6: ['bottom', 'top'],
    7: ['left', 'top'],
    8: ['top', 'left'],
    9: ['bottom', 'top'],
    11: ['right', 'top'],
    12: ['left', 'right'],
    13: ['bottom', 'right'],
    14: ['left', 'bottom'],
  };
  const AMBIGUOUS = {
    5: [
      ['left', 'bottom'],
      ['right', 'top'],
    ],
    10: [
      ['bottom', 'right'],
      ['top', 'left'],
    ],
  };
  for (let j = 0; j < ny; j++) {
    for (let i = 0; i < nx; i++) {
      const xL = x0 + i * dx,
        xR = x0 + (i + 1) * dx;
      const yB = y0 + j * dy,
        yT = y0 + (j + 1) * dy;
      const bl = grid[j][i],
        br = grid[j][i + 1],
        tr = grid[j + 1][i + 1],
        tl = grid[j + 1][i];
      const c =
        (bl > threshold ? 1 : 0) |
        (br > threshold ? 2 : 0) |
        (tr > threshold ? 4 : 0) |
        (tl > threshold ? 8 : 0);
      if (c === 0 || c === 15) continue;
      const edgePoint = {
        bottom: () => [lerp(xL, xR, bl, br), yB],
        right: () => [xR, lerp(yB, yT, br, tr)],
        top: () => [lerp(xL, xR, tl, tr), yT],
        left: () => [xL, lerp(yB, yT, bl, tl)],
      };
      const pairs = AMBIGUOUS[c] ? AMBIGUOUS[c] : [CASES[c]];
      // Orient every segment the same way — the >threshold side on its LEFT. The CASES table
      // above doesn't (case 1 and case 14 are inverses of each other yet list the same edge
      // pair), and without a consistent winding the border-closing below has no way to tell
      // which way around the window encloses the pattern rather than its negative.
      const corners = [
        [xL, yB, bl],
        [xR, yB, br],
        [xR, yT, tr],
        [xL, yT, tl],
      ].filter((k) => k[2] > threshold);
      for (const [a, b] of pairs) {
        const A = edgePoint[a](),
          B = edgePoint[b]();
        const mx = (A[0] + B[0]) / 2,
          my = (A[1] + B[1]) / 2;
        // the nearest inside corner is always one this segment separates, so its side is the
        // inside side even for the two-segment ambiguous cases
        let near = null,
          best = Infinity;
        for (const k of corners) {
          const d = (k[0] - mx) ** 2 + (k[1] - my) ** 2;
          if (d < best) {
            best = d;
            near = k;
          }
        }
        const cross =
          near === null ? 1 : (B[0] - A[0]) * (near[1] - A[1]) - (B[1] - A[1]) * (near[0] - A[0]);
        segments.push(cross < 0 ? { a: B, b: A } : { a: A, b: B });
      }
    }
  }

  const key = ([x, y]) => Math.round(x * 500) + ',' + Math.round(y * 500);
  const byStart = new Map(),
    byEnd = new Map();
  segments.forEach((seg, id) => {
    const ks = key(seg.a),
      ke = key(seg.b);
    if (!byStart.has(ks)) byStart.set(ks, []);
    byStart.get(ks).push(id);
    if (!byEnd.has(ke)) byEnd.set(ke, []);
    byEnd.get(ke).push(id);
  });
  const usedSeg = new Array(segments.length).fill(false);
  const loops = [];
  const open = [];
  for (let id0 = 0; id0 < segments.length; id0++) {
    if (usedSeg[id0]) continue;
    usedSeg[id0] = true;
    const chain = [segments[id0].a, segments[id0].b];
    let closed = false;
    for (let guard = 0; guard < 200000; guard++) {
      const tailKey = key(chain[chain.length - 1]);
      if (tailKey === key(chain[0]) && chain.length > 2) {
        closed = true;
        break;
      }
      const next = (byStart.get(tailKey) || []).find((id) => !usedSeg[id]);
      if (next === undefined) break;
      usedSeg[next] = true;
      chain.push(segments[next].b);
    }
    // Walk backwards too: the seed segment is rarely the head of its chain, and leaving the
    // head dangling used to turn every open contour into a fragment that got discarded.
    if (!closed)
      for (let guard = 0; guard < 200000; guard++) {
        const prev = (byEnd.get(key(chain[0])) || []).find((id) => !usedSeg[id]);
        if (prev === undefined) break;
        usedSeg[prev] = true;
        chain.unshift(segments[prev].a);
      }
    if (closed) {
      chain.pop(); // drop the duplicate closing point — toD() closes with Z
      if (chain.length >= 3) loops.push(chain);
    } else if (chain.length >= 2) {
      open.push(chain);
    }
  }
  return loops.concat(
    closeOpenChains(open, x0, y0, x0 + nx * dx, y0 + ny * dy, Math.min(dx, dy) * 0.5),
  );
}

/**
 * Close the contour chains that run off the edge of the sampled window, by joining them along
 * the window border.
 *
 * These used to be discarded, on the theory that padding made them rare. It doesn't: a branching
 * stripe field spans the window, so most of its contours *can't* close inside it (zebra kept 77
 * closed loops and dropped 261 open chains), and which fragments happened to survive was not
 * translation-invariant — that's what broke the tiling guarantee the header comment claims.
 *
 * Every chain is wound with the pattern's interior on its left, so walking the border
 * counter-clockwise from one chain's tail to the next chain's head keeps that same interior on
 * the left the whole way round. Chains are chained head-to-tail in border order rather than each
 * closing back on itself, which is what keeps two chains from both claiming the same border run.
 */
function closeOpenChains(chains, xmin, ymin, xmax, ymax, eps) {
  const w = xmax - xmin,
    h = ymax - ymin;
  const P = 2 * (w + h);
  // CCW perimeter coordinate: bottom left→right, right edge up, top right→left, left edge down.
  const param = ([x, y]) => {
    if (Math.abs(y - ymin) <= eps) return x - xmin;
    if (Math.abs(x - xmax) <= eps) return w + (y - ymin);
    if (Math.abs(y - ymax) <= eps) return w + h + (xmax - x);
    if (Math.abs(x - xmin) <= eps) return 2 * w + h + (ymax - y);
    return null; // not on the border — chain ended somewhere it shouldn't have
  };
  const CORNERS = [
    [0, [xmin, ymin]],
    [w, [xmax, ymin]],
    [w + h, [xmax, ymax]],
    [2 * w + h, [xmin, ymax]],
  ];

  const items = [];
  for (const c of chains) {
    const head = param(c[0]),
      tail = param(c[c.length - 1]);
    if (head === null || tail === null) continue; // degenerate; drop as before
    items.push({ pts: c, head, tail, used: false });
  }
  const out = [];
  for (const start of items) {
    if (start.used) continue;
    const loop = [];
    let cur = start;
    for (let guard = 0; guard < items.length + 1; guard++) {
      cur.used = true;
      loop.push(...cur.pts);
      // the next chain head strictly ahead of this tail in CCW order (cyclic)
      let next = null,
        bestGap = Infinity;
      for (const it of items) {
        const gap = (it.head - cur.tail + P) % P;
        if (gap < bestGap) {
          bestGap = gap;
          next = it;
        }
      }
      if (!next) break;
      for (const [t, pt] of CORNERS)
        if ((t - cur.tail + P) % P > 0 && (t - cur.tail + P) % P < bestGap) loop.push(pt);
      if (next === start) break;
      if (next.used) break; // shouldn't happen; bail rather than loop forever
      cur = next;
    }
    if (loop.length >= 3) out.push(loop);
  }
  return out;
}

/**
 * Thin an over-sampled contour, keeping the result tileable.
 *
 * Marching squares emits a vertex on every grid edge the contour crosses — at res 3 that is one
 * every 0.33mm along a smooth curve, and zebra shipped 13.6k of them. Vertex count is what decides
 * whether Fill mode's tile union survives: turf 6.5's polygon-clipping fails somewhere around
 * 800k vertices in one operation, and the app asks for 143 tiles of a 60mm pattern to cover a chair
 * zone, so 13.6k/tile blew straight through it and half the tiles were silently dropped.
 *
 * Douglas-Peucker can't be used here. It picks vertices to keep from the *whole chain*, and the
 * chains this runs on are cut arbitrarily by the sampling window, so the same stretch of contour
 * appearing near x=0 and again near x=60 (the field is periodic) would be thinned differently and
 * the two sides of the seam would stop lining up. The rule below is purely local and symmetric —
 * a vertex is dropped only if it sits within `eps` of the line joining its own two neighbours and
 * is the flattest of that trio — so it depends on nothing but the geometry within two vertices,
 * which is identical for both periodic copies. Ties break on the neighbours' relative coordinates,
 * which translation preserves. Passes are capped because each one can move the outline by up to
 * `eps`; the drop between passes is measured in tests/patterns-assets.test.ts.
 *
 * No test asserts the output stays a simple polygon (no self-crossings) — `turf.kinks()` isn't a
 * usable oracle for that here: the clipped loops this runs on legitimately touch the tile's own
 * boundary at more than one point (a motif clipped against the same edge at different y values),
 * which `turf.kinks()` also reports as a kink even though it isn't a crossing. What's actually
 * verified is empirical — the seam-continuity test plus the "builds with no warnings" measurement
 * in docs/tech-debt.md — not a geometric proof.
 */
function thinContourLoop(loop, eps, maxPasses = 12) {
  let pts = loop;
  for (let pass = 0; pass < maxPasses && pts.length > 8; pass++) {
    const n = pts.length;
    const flat = new Array(n);
    for (let i = 0; i < n; i++) {
      const a = pts[(i - 1 + n) % n],
        p = pts[i],
        b = pts[(i + 1) % n];
      const dx = b[0] - a[0],
        dy = b[1] - a[1];
      const len = Math.hypot(dx, dy);
      flat[i] = len < 1e-12 ? 0 : Math.abs(dx * (a[1] - p[1]) - dy * (a[0] - p[0])) / len;
    }
    // Strictly-flatter-than-both-neighbours keeps the survivors spread out instead of collapsing
    // a whole run at once, and makes the choice independent of where the loop happens to start.
    const rank = (i) => [flat[i], pts[i][0], pts[i][1]];
    const flatter = (i, j) => {
      const [fa, xa, ya] = rank(i),
        [fb, xb, yb] = rank(j);
      return fa !== fb ? fa < fb : xa !== xb ? xa < xb : ya < yb;
    };
    const keep = pts.filter((_, i) => {
      if (flat[i] >= eps) return true;
      const prev = (i - 1 + n) % n,
        next = (i + 1) % n;
      return !(flatter(i, prev) && flatter(i, next));
    });
    if (keep.length === n) break;
    pts = keep;
  }
  return pts;
}

const n2 = (v) => Math.round(v * 100) / 100;
const toD = (loop) => loop.map(([x, y], i) => `${i ? 'L' : 'M'}${n2(x)} ${n2(y)}`).join(' ') + ' Z';
const MIN_AREA = 0.2; // mm² — drops degenerate slivers Sutherland-Hodgman leaves at a corner
// The field path needs a real degeneracy epsilon instead: its contours aren't drawn at 9 wrap
// positions, so every clipped piece is genuine content, and a stripe that barely pokes over a
// tile edge leaves a legitimate sliver on the far side. Dropping those at 0.2mm² is what left
// zebra with ink meeting white across the seam.
const MIN_AREA_FIELD = 1e-6;

/**
 * Render one pattern on a WxH tile: an optional full-bleed background field, then `count`
 * motifs (blobs or streaks) placed at random positions/rotations, each wrap-and-clipped at
 * all 9 positions of a 3x3 torus wrap so the tile repeats seamlessly. One <path> per
 * surviving piece, same fill — the app's per-color region union (computeNetRegionsByColor)
 * merges them and nets the background against the motif via document order, no reliance on
 * fill-rule for overlaps between separately-wrapped pieces.
 */
function renderPattern(p) {
  const { seed, W, H, shape, motifFill, bg } = p;
  const rng = mulberry32(seed);
  const paths = [];
  if (bg)
    paths.push({
      d: toD([
        [0, 0],
        [W, 0],
        [W, H],
        [0, H],
      ]),
      fill: bg,
    });

  if (shape === 'field') {
    const field = stripeField(rng, p.field);
    const loops = marchingSquaresContours(field, W, H, {
      res: p.res ?? 2.5,
      padMM: p.padMM ?? 20,
      threshold: p.threshold ?? 0.5,
    });
    // One <path> with every contour as a subpath, not one path per contour: a stripe field has
    // enclosed white islands, and the app resolves hole-vs-solid by containment *within a
    // shape* (shapeToFeature in src/geometry/regions.ts). Split across separate paths each
    // island would union back into its stripe and fill in solid.
    const subpaths = [];
    for (const loop of loops) {
      // Thinned before the clip, not after: a clipped piece has been cut at the tile edge, and
      // simplifying from that cut would let the two sides of a seam diverge.
      const clipped = clipToRect(thinContourLoop(loop, p.simplifyEps ?? 0), 0, 0, W, H);
      if (clipped.length >= 3 && shoelaceArea(clipped) > MIN_AREA_FIELD)
        subpaths.push(toD(clipped));
    }
    if (subpaths.length) paths.push({ d: subpaths.join(' '), fill: motifFill });
  } else {
    const { count, motif, rotBase = 0, rotSpread = Math.PI } = p;
    for (let i = 0; i < count; i++) {
      const cx = rng() * W;
      const cy = rng() * H;
      const local = shape === 'streak' ? streak(rng, motif(rng)) : noisyBlob(rng, motif(rng));
      const rot = rotBase + (rng() - 0.5) * 2 * rotSpread;
      const cosr = Math.cos(rot),
        sinr = Math.sin(rot);
      const rotated = local.map(([x, y]) => [x * cosr - y * sinr, x * sinr + y * cosr]);
      for (const dx of [-1, 0, 1])
        for (const dy of [-1, 0, 1]) {
          const shifted = rotated.map(([x, y]) => [x + cx + dx * W, y + cy + dy * H]);
          const clipped = clipToRect(shifted, 0, 0, W, H);
          if (clipped.length >= 3 && shoelaceArea(clipped) > MIN_AREA)
            paths.push({ d: toD(clipped), fill: motifFill });
        }
    }
  }

  return `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<svg width="${W}mm" height="${H}mm" viewBox="0 0 ${W} ${H}" version="1.1"
     xmlns="http://www.w3.org/2000/svg">
${paths.map((pth) => `  <path d="${pth.d}" fill="${pth.fill}"/>`).join('\n')}
</svg>
`;
}

