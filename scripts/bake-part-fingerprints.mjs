// Seals every part in public/stl/parts.json with a mesh fingerprint (triangle count + bbox hash),
// so the export placement lookup (src/export/placement.ts) can refuse to apply a baked plateR/
// fixedPos/primeTowerDelta to a mesh those numbers weren't verified against. Same "bake, don't
// derive at runtime" rule as bake-chair-placement.mjs and bake-zones.mjs.
//
// This does NOT re-verify placement — it only records the fingerprint of whatever is currently in
// public/stl/. Re-pack a part (scripts/pack-part.mjs) or change its placement in
// src/export/chairPlacement.ts / src/export/threemf.ts, re-verify the print pose in the slicer
// FIRST, then re-run this to reseal:
//
//   npx vite-node scripts/bake-part-fingerprints.mjs
//
// Uses the runtime's own meshFingerprint (src/geometry/zoneCharts.ts) rather than a second
// implementation, so the seal this writes is exactly what the app will recompute at load time.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { readMesh } from './lib/mesh.mjs';
import { meshFingerprint } from '../src/geometry/zoneCharts.ts';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(REPO, 'src/export/partFingerprints.ts');

const manifest = JSON.parse(fs.readFileSync(path.join(REPO, 'public/stl/parts.json'), 'utf8'));

const rows = [];
for (const entry of manifest) {
  const positions = await readMesh(path.join(REPO, 'public', entry.file));
  const triCount = positions.length / 9;
  const fp = meshFingerprint(positions, triCount);
  rows.push({ id: entry.id, ...fp });
  console.log(`  ${entry.id.padEnd(26)} tris ${String(triCount).padStart(6)}  ${fp.bboxHash}`);
}

rows.sort((a, b) => a.id.localeCompare(b.id));

// The generated file is checked in and `format:check` runs over it in CI, so it has to come out of
// here already formatted -- Prettier's default quoteProps ("as-needed") strips the quotes from a key
// that's a valid identifier (`footrest`) while keeping them on the hyphenated ones.
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const key = (id) => (IDENTIFIER.test(id) ? id : `'${id}'`);

const body = rows
  .map((r) => `  ${key(r.id)}: { triangleCount: ${r.triangleCount}, bboxHash: '${r.bboxHash}' },`)
  .join('\n');

const out = `// GENERATED by scripts/bake-part-fingerprints.mjs -- do not hand-edit.
//
// One mesh fingerprint (triangle count + bbox hash, src/geometry/zoneCharts.ts meshFingerprint)
// per public/stl/parts.json entry, sealing the mesh src/export/placement.ts's baked plateR/
// fixedPos/primeTowerDelta/objectSettings were verified against. A part whose loaded mesh doesn't
// match its seal here loses its baked placement rather than having it silently misapplied — see
// resolvePlacement in src/export/placement.ts.
//
// Sealing is "same mesh file", not "same part": a CAD re-export of the identical part at a
// different triangle count fails this seal even though its orientation/extents (and so plateR)
// would still be correct. That's deliberate -- a looser check would be a second, weaker
// verification method living next to zoneCharts.ts's, and re-packing a part already means
// re-verifying its placement in the slicer, which is the moment to reseal too.
//
// Regenerate: npx vite-node scripts/bake-part-fingerprints.mjs

export const PART_FINGERPRINTS: Record<string, { triangleCount: number; bboxHash: string }> = {
${body}
};
`;

fs.writeFileSync(OUT, out);
console.log(`\n  wrote ${OUT} -- ${rows.length} parts`);
